-- ---------------------------------------------------------------------
-- Users & roles  (FR-01, FR-02, FR-16)
-- ---------------------------------------------------------------------
CREATE TABLE users (
  id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  full_name     VARCHAR(120)        NOT NULL,
  email         VARCHAR(150)        NOT NULL UNIQUE,
  username      VARCHAR(60)         NOT NULL UNIQUE,
  password_hash VARCHAR(255)        NOT NULL,
  role          ENUM('resident','drrmo','admin') NOT NULL DEFAULT 'resident',
  barangay      VARCHAR(100)        NULL,
  contact_no    VARCHAR(30)         NULL,
  is_active     TINYINT(1)          NOT NULL DEFAULT 1,
  failed_logins TINYINT UNSIGNED    NOT NULL DEFAULT 0,
  locked_until  DATETIME            NULL,
  last_login_at DATETIME            NULL,       -- server timestamp of the account's most recent successful login
  created_at    DATETIME            NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME            NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- NOTE: the default Administrator account is NOT seeded here because a
