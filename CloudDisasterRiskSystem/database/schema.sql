-- ---------------------------------------------------------------------
-- Incident reports  (FR-09, FR-10)
-- ---------------------------------------------------------------------
CREATE TABLE incident_reports (
  id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  reporter_id   INT UNSIGNED       NOT NULL,
  hazard_type   VARCHAR(60)        NOT NULL,   -- flood, fire, landslide, earthquake, storm, etc.
  severity      ENUM('low','moderate','high','critical') NOT NULL DEFAULT 'low',
  description   TEXT               NULL,
  latitude      DECIMAL(10,7)      NOT NULL,
  longitude     DECIMAL(10,7)      NOT NULL,
  barangay_id   INT UNSIGNED       NULL,
  photo_path    VARCHAR(255)       NULL,
  status        ENUM('pending','approved','declined') NOT NULL DEFAULT 'pending',
  moderation_note VARCHAR(255)     NULL,
  moderated_by  INT UNSIGNED       NULL,
  moderated_at  DATETIME           NULL,
  created_at    DATETIME           NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (reporter_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (barangay_id) REFERENCES barangays(id) ON DELETE SET NULL,
  FOREIGN KEY (moderated_by) REFERENCES users(id) ON DELETE SET NULL,
  INDEX idx_status (status),
  INDEX idx_hazard (hazard_type),
  INDEX idx_location (latitude, longitude)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Geospatial layers  (FR-05, FR-11, FR-12) — stores uploaded GeoJSON
-- ---------------------------------------------------------------------
CREATE TABLE geo_layers (
  id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name          VARCHAR(150)       NOT NULL,
  layer_type    ENUM('hazard_zone','barangay_boundary','evacuation_route','baseline_dataset','other')
                NOT NULL DEFAULT 'other',
  description   VARCHAR(255)       NULL,
  geojson       LONGTEXT           NOT NULL,   -- raw GeoJSON FeatureCollection
  source_format ENUM('geojson','shapefile','csv') NOT NULL DEFAULT 'geojson',
  uploaded_by   INT UNSIGNED       NOT NULL,
  is_visible    TINYINT(1)         NOT NULL DEFAULT 1,
  created_at    DATETIME           NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME           NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (uploaded_by) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Notifications  (FR-17)
-- ---------------------------------------------------------------------
CREATE TABLE notifications (
  id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id     INT UNSIGNED   NOT NULL,
  message     VARCHAR(255)   NOT NULL,
  is_read     TINYINT(1)     NOT NULL DEFAULT 0,
  created_at  DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- AI: Hotspot detection run log  (FR-19, NFR-14)
-- ---------------------------------------------------------------------
CREATE TABLE hotspot_runs (
  id              INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  algorithm       ENUM('dbscan') NOT NULL DEFAULT 'dbscan',
  eps_meters      INT UNSIGNED   NOT NULL,
  min_points      TINYINT UNSIGNED NOT NULL,
  window_days     SMALLINT UNSIGNED NOT NULL,
  input_count     INT UNSIGNED   NOT NULL,
  cluster_count   INT UNSIGNED   NOT NULL,
  result_json     LONGTEXT       NOT NULL,     -- cached ranked hotspot list + GeoJSON
  run_by          INT UNSIGNED   NULL,
  created_at      DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (run_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- AI: Predictive risk model results  (FR-20, Phase 2, NFR-15)
-- ---------------------------------------------------------------------
CREATE TABLE forecast_runs (
  id                INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  method            VARCHAR(40)   NOT NULL DEFAULT 'linear_trend',
  barangay_id       INT UNSIGNED  NULL,
  backtest_mae      DECIMAL(8,3)  NULL,        -- mean absolute error from backtest
  backtest_accepted TINYINT(1)    NOT NULL DEFAULT 0, -- passed NFR-15 threshold?
  threshold_mae     DECIMAL(8,3)  NOT NULL DEFAULT 2.0,
  result_json       LONGTEXT      NOT NULL,
  run_by            INT UNSIGNED  NULL,
  created_at        DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (barangay_id) REFERENCES barangays(id) ON DELETE SET NULL,
  FOREIGN KEY (run_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Historical reported cases (Reported Cases tab) — a normalized import of
-- an external multi-hazard historical dataset (2000-2026), independent of
-- the live incident_reports table (which holds user-submitted reports
-- going through moderation). This is long-run reference data used for
-- trend/prediction analysis at a scale live reporting can't yet provide.
-- Populated via database/import_historical_cases.php, never through the
-- public report form.
-- ---------------------------------------------------------------------
CREATE TABLE historical_cases (
  id                    INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  incident_ref          VARCHAR(20)    NOT NULL,   -- source dataset's own ID (e.g. INC000001)
  occurred_on           DATE           NOT NULL,
  year                  SMALLINT UNSIGNED NOT NULL,
  month                 TINYINT UNSIGNED NOT NULL,
  district              VARCHAR(30)    NOT NULL,   -- North Caloocan / South Caloocan
  barangay              VARCHAR(20)    NOT NULL,   -- source dataset's own barangay label/number
  hazard_type           VARCHAR(30)    NOT NULL,   -- normalized to this app's hazard tags
  severity              ENUM('low','moderate','high','critical') NOT NULL,
  latitude              DECIMAL(10,7)  NOT NULL,
  longitude             DECIMAL(10,7)  NOT NULL,
  affected_population   INT UNSIGNED   NOT NULL DEFAULT 0,
  casualties             INT UNSIGNED  NOT NULL DEFAULT 0,
  injuries              INT UNSIGNED   NOT NULL DEFAULT 0,
  estimated_damage_php  DECIMAL(14,2)  NOT NULL DEFAULT 0,
  response_time_minutes INT UNSIGNED   NULL,
  weather_condition     VARCHAR(30)    NULL,       -- flood-related rows only
  magnitude             DECIMAL(4,2)   NULL,       -- earthquake rows only
  crime_category        VARCHAR(30)    NULL,       -- crime rows only
  fire_cause            VARCHAR(30)    NULL,       -- fire rows only
  created_at            DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uniq_incident_ref (incident_ref),
  INDEX idx_occurred (occurred_on),
  INDEX idx_hazard (hazard_type),
  INDEX idx_barangay (barangay),
  INDEX idx_location (latitude, longitude)
) ENGINE=InnoDB;

